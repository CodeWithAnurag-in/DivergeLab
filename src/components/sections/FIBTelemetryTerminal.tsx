import React, { useState, useMemo } from 'react';
import { HudHeader } from '../common/HudHeader';
import {
  type NodeId,
  type GraphNode,
  type GraphEdge,
} from '../../types/routing';
import {
  INITIAL_NODES,
  INITIAL_EDGES,
  generateFIBTelemetries,
} from '../../utils/graphAlgorithms';
import {
  Terminal,
  HardDrive,
  Clock,
  Send,
  Zap
} from 'lucide-react';

export const FIBTelemetryTerminal: React.FC = () => {
  const [nodes] = useState<GraphNode[]>(INITIAL_NODES);
  const [edges, setEdges] = useState<GraphEdge[]>(INITIAL_EDGES);
  const [destNode, setDestNode] = useState<NodeId>('F');
  const [isChurning, setIsChurning] = useState<boolean>(false);
  const [traceLog, setTraceLog] = useState<string[]>([]);
  const [isTracing, setIsTracing] = useState<boolean>(false);

  // Compute live FIB tables from true graph adjacency
  const { linkState: lsFib, distanceVector: dvFib } = useMemo(() => {
    return generateFIBTelemetries(nodes, edges);
  }, [nodes, edges]);

  // Topology flap stress test
  const triggerTopologyChurn = () => {
    setIsChurning(true);
    setTraceLog(prev => [
      `[EVENT] Topology Churn Injected: Interface eth0 (Link A-B) carrier flapped.`,
      `[OSPF] LSA Type 1 Flooded via Multicast 224.0.0.5 across all active adjacencies.`,
      `[OSPF] Full Dijkstra SPF recalculated in 14.8ms. FIB updated seamlessly with zero loops.`,
      `[RIPv2] Triggered update dispatched to 224.0.0.9. Awaiting neighbor holddown timers (180s invalid timer)...`,
      ...prev.slice(0, 10)
    ]);

    // Flap link A-B temporarily
    setEdges(prev => prev.map(e => e.id === 'A-B' ? { ...e, isSevered: true } : e));
    setTimeout(() => {
      setEdges(prev => prev.map(e => e.id === 'A-B' ? { ...e, isSevered: false } : e));
      setIsChurning(false);
    }, 2400);
  };

  // Run live probe / traceroute lookup across synthesized FIB
  const executeTraceroute = () => {
    if (isTracing) return;
    setIsTracing(true);
    const target = nodes.find(n => n.id === destNode)!;

    const lsEntry = lsFib.entries.find(e => e.destinationNode === destNode);
    const dvEntry = dvFib.entries.find(e => e.destinationNode === destNode);

    const logLines = [
      `=== HARDWARE FIB FORWARDING LOOKUP: INGRESS PACKET TO ${target.ip} ===`,
      `[LS-FIB LOOKUP] Destination Prefix: ${lsEntry?.prefix} | Next-Hop IP: ${lsEntry?.nextHopIp} | Outgoing Interface: ${lsEntry?.interfaceName} | Metric: ${lsEntry?.metric}`,
      `[LS-FIB ASIC] Hardware TCAM Match: 0.038ms | Convergence Latency (Δt): 14.8ms | Status: ${lsEntry?.status}`,
      `[DV-FIB LOOKUP] Destination Prefix: ${dvEntry?.prefix} | Next-Hop IP: ${dvEntry?.nextHopIp} | Outgoing Interface: ${dvEntry?.interfaceName} | Metric: ${dvEntry?.metric}`,
      `[DV-FIB ASIC] Software Route Table Scan | Convergence Latency (Δt): 4,200.0ms | Status: ${dvEntry?.status}`,
      `[EGRESS RESULT] Packet dispatched out ${lsEntry?.interfaceName} with MAC header rewrite. TTL 64 → 63.`
    ];

    setTraceLog(prev => [...logLines, ...prev.slice(0, 12)]);
    setTimeout(() => setIsTracing(false), 800);
  };

  return (
    <section id="fib-telemetry-terminal" className="relative w-full bg-black py-16 px-4 sm:px-8 border-t border-white/10">
      <div className="max-w-7xl mx-auto">
        <HudHeader
          badgeNumber="SECTION 06"
          badgeLabel="FIB TELEMETRY"
          title="FORWARDING INFORMATION BASE (FIB) TELEMETRY TERMINAL"
          subtitle="Side-by-side terminal inspector comparing kernel forwarding tables generated by both algorithms. The Forwarding Information Base is what the silicon switch fabrics and OS network stacks actually query at line rate."
          rightSlot={
            <div className="flex items-center gap-2">
              <button
                onClick={triggerTopologyChurn}
                disabled={isChurning}
                className="px-3.5 py-1.5 rounded-lg bg-white/5 hover:bg-white/10 border border-white/10 text-white font-['JetBrains_Mono'] text-xs font-bold flex items-center gap-2 disabled:opacity-50 transition-all cursor-pointer"
              >
                <Zap className="w-3.5 h-3.5 text-zinc-400" />
                {isChurning ? 'Churn Flapping...' : 'Inject Topology Churn'}
              </button>
            </div>
          }
        />

        {/* Real-time Hardware Metrics Telemetry Grid */}
        <div className="grid grid-cols-2 md:grid-cols-4 gap-4 mb-8 font-['JetBrains_Mono']">
          <div className="bg-zinc-950/80 border border-white/10 rounded-xl p-4 backdrop-blur-md">
            <div className="flex items-center justify-between text-zinc-500 text-[10px] uppercase mb-1">
              <span>LS Convergence Latency (Δt)</span>
              <Clock className="w-3.5 h-3.5 text-white" />
            </div>
            <div className="text-xl font-bold text-white">{lsFib.convergenceTimeMs} ms</div>
            <div className="text-[10px] text-zinc-500 font-['Geist'] mt-0.5">Sub-second local SPF calculation</div>
          </div>

          <div className="bg-zinc-950/80 border border-white/10 rounded-xl p-4 backdrop-blur-md">
            <div className="flex items-center justify-between text-zinc-500 text-[10px] uppercase mb-1">
              <span>DV Convergence Latency (Δt)</span>
              <Clock className="w-3.5 h-3.5 text-zinc-400" />
            </div>
            <div className="text-xl font-bold text-zinc-200">{dvFib.convergenceTimeMs.toLocaleString()} ms</div>
            <div className="text-[10px] text-zinc-500 font-['Geist'] mt-0.5">Bound by periodic timer rounds</div>
          </div>

          <div className="bg-zinc-950/80 border border-white/10 rounded-xl p-4 backdrop-blur-md">
            <div className="flex items-center justify-between text-zinc-500 text-[10px] uppercase mb-1">
              <span>LS RAM Footprint</span>
              <HardDrive className="w-3.5 h-3.5 text-white" />
            </div>
            <div className="text-xl font-bold text-white">{lsFib.memoryKb} KB</div>
            <div className="text-[10px] text-zinc-500 font-['Geist'] mt-0.5">Stores full graph LSDB + SPF tree</div>
          </div>

          <div className="bg-zinc-950/80 border border-white/10 rounded-xl p-4 backdrop-blur-md">
            <div className="flex items-center justify-between text-zinc-500 text-[10px] uppercase mb-1">
              <span>DV RAM Footprint</span>
              <HardDrive className="w-3.5 h-3.5 text-zinc-400" />
            </div>
            <div className="text-xl font-bold text-zinc-200">{dvFib.memoryKb} KB</div>
            <div className="text-[10px] text-zinc-500 font-['Geist'] mt-0.5">Only stores 1D vector of next-hops</div>
          </div>
        </div>

        {/* Side-by-Side Kernel Forwarding Tables */}
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-6 mb-8">
          
          {/* Left: Link-State Kernel FIB */}
          <div className="bg-zinc-950/90 border border-white/10 rounded-2xl p-5 backdrop-blur-xl shadow-[0_0_30px_rgba(255,255,255,0.02)]">
            <div className="flex items-center justify-between mb-4 pb-3 border-b border-white/10">
              <div className="flex items-center gap-2">
                <span className="w-1.5 h-1.5 rounded-full bg-white shadow-[0_0_8px_rgba(255,255,255,0.8)]" />
                <span className="font-['JetBrains_Mono'] text-xs font-bold text-white uppercase tracking-wider">
                  KERNEL FIB // LINK-STATE (OSPF / DIJKSTRA)
                </span>
              </div>
              <div className="flex items-center gap-2 text-[10px] font-['JetBrains_Mono'] text-zinc-400">
                <span>Δt: <strong className="text-white">{lsFib.convergenceTimeMs}ms</strong></span>
                <span>•</span>
                <span>RAM: <strong className="text-white">{lsFib.memoryKb}KB</strong></span>
              </div>
            </div>

            <div className="overflow-x-auto">
              <table className="w-full text-left font-['JetBrains_Mono'] text-xs">
                <thead>
                  <tr className="border-b border-white/10 text-zinc-500 text-[10px] uppercase tracking-wider">
                    <th className="pb-2">Destination Prefix</th>
                    <th className="pb-2">Next-Hop IP</th>
                    <th className="pb-2">Outgoing Interface</th>
                    <th className="pb-2">Metric</th>
                    <th className="pb-2 text-right">Route Status</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-white/5">
                  {lsFib.entries.map((entry, idx) => (
                    <tr key={idx} className="hover:bg-white/[0.02] transition-colors">
                      <td className="py-2.5 font-bold text-white">{entry.prefix}</td>
                      <td className="py-2.5 text-zinc-300">{entry.nextHopIp}</td>
                      <td className="py-2.5 text-zinc-400">{entry.interfaceName}</td>
                      <td className="py-2.5 text-zinc-300">{entry.metric}</td>
                      <td className="py-2.5 text-right">
                        <span className={`text-[10px] px-2 py-0.5 rounded font-bold ${
                          entry.status === 'ACTIVE'
                            ? 'bg-white/10 text-white border border-white/20'
                            : 'bg-white/5 text-zinc-500 border border-white/5'
                        }`}>
                          {entry.status}
                        </span>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>

            <div className="mt-4 pt-3 border-t border-white/10 flex items-center justify-between text-[11px] font-['JetBrains_Mono'] text-zinc-500">
              <span>Routing Protocol: OSPFv2 (Protocol 89)</span>
              <span className="text-zinc-400 font-bold">Total Entries: {lsFib.entries.length}</span>
            </div>
          </div>

          {/* Right: Distance-Vector Kernel FIB */}
          <div className="bg-zinc-950/90 border border-white/10 rounded-2xl p-5 backdrop-blur-xl shadow-[0_0_30px_rgba(255,255,255,0.02)]">
            <div className="flex items-center justify-between mb-4 pb-3 border-b border-white/10">
              <div className="flex items-center gap-2">
                <span className="w-1.5 h-1.5 rounded-full bg-white shadow-[0_0_8px_rgba(255,255,255,0.8)]" />
                <span className="font-['JetBrains_Mono'] text-xs font-bold text-white uppercase tracking-wider">
                  KERNEL FIB // DISTANCE-VECTOR (RIPv2 / BELLMAN-FORD)
                </span>
              </div>
              <div className="flex items-center gap-2 text-[10px] font-['JetBrains_Mono'] text-zinc-400">
                <span>Δt: <strong className="text-zinc-200">{dvFib.convergenceTimeMs.toLocaleString()}ms</strong></span>
                <span>•</span>
                <span>RAM: <strong className="text-white">{dvFib.memoryKb}KB</strong></span>
              </div>
            </div>

            <div className="overflow-x-auto">
              <table className="w-full text-left font-['JetBrains_Mono'] text-xs">
                <thead>
                  <tr className="border-b border-white/10 text-zinc-500 text-[10px] uppercase tracking-wider">
                    <th className="pb-2">Destination Prefix</th>
                    <th className="pb-2">Next-Hop IP</th>
                    <th className="pb-2">Outgoing Interface</th>
                    <th className="pb-2">Hops</th>
                    <th className="pb-2 text-right">Route Status</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-white/5">
                  {dvFib.entries.map((entry, idx) => (
                    <tr key={idx} className="hover:bg-white/[0.02] transition-colors">
                      <td className="py-2.5 font-bold text-white">{entry.prefix}</td>
                      <td className="py-2.5 text-zinc-300">{entry.nextHopIp}</td>
                      <td className="py-2.5 text-zinc-400">{entry.interfaceName}</td>
                      <td className="py-2.5 text-zinc-300">{entry.metric}</td>
                      <td className="py-2.5 text-right">
                        <span className={`text-[10px] px-2 py-0.5 rounded font-bold ${
                          entry.status === 'ACTIVE'
                            ? 'bg-white/10 text-white border border-white/20'
                            : 'bg-white/5 text-zinc-500 border border-white/5'
                        }`}>
                          {entry.status}
                        </span>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>

            <div className="mt-4 pt-3 border-t border-white/10 flex items-center justify-between text-[11px] font-['JetBrains_Mono'] text-zinc-500">
              <span>Routing Protocol: RIPv2 (RFC 2453)</span>
              <span className="text-zinc-400 font-bold">Total Entries: {dvFib.entries.length}</span>
            </div>
          </div>

        </div>

        {/* Live Packet Traceroute & Lookup Simulator */}
        <div className="bg-zinc-950 border border-white/10 rounded-2xl p-6 backdrop-blur-xl">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-4 pb-4 border-b border-white/10">
            <div>
              <div className="flex items-center gap-2">
                <Terminal className="w-4 h-4 text-white" />
                <h3 className="font-['Plus_Jakarta_Sans'] font-bold text-white text-base uppercase tracking-tight">
                  LIVE PACKET PROBE &amp; FIB LOOKUP SIMULATOR
                </h3>
              </div>
              <p className="font-['Geist'] text-zinc-400 text-xs mt-0.5">
                Inject an IPv4 packet from Ingress Router A to any destination and inspect the hardware FIB lookup resolution across both control planes.
              </p>
            </div>

            {/* Target Node Picker & Probe Trigger */}
            <div className="flex items-center gap-3">
              <span className="font-['JetBrains_Mono'] text-xs text-zinc-500 uppercase">DESTINATION:</span>
              <div className="flex gap-1">
                {(['B', 'C', 'D', 'E', 'F'] as NodeId[]).map(nid => (
                  <button
                    key={nid}
                    onClick={() => setDestNode(nid)}
                    className={`w-7 h-7 rounded font-['JetBrains_Mono'] text-xs font-bold transition-all cursor-pointer ${
                      destNode === nid
                        ? 'bg-white text-black shadow-[0_0_10px_rgba(255,255,255,0.4)]'
                        : 'bg-white/5 text-zinc-400 hover:text-white'
                    }`}
                  >
                    {nid}
                  </button>
                ))}
              </div>

              <button
                onClick={executeTraceroute}
                disabled={isTracing}
                className="px-4 py-2 rounded-lg bg-white text-black font-['JetBrains_Mono'] text-xs font-extrabold flex items-center gap-1.5 disabled:opacity-50 transition-all hover:bg-zinc-200 cursor-pointer shadow-[0_0_15px_rgba(255,255,255,0.08)]"
              >
                <Send className="w-3.5 h-3.5" />
                Lookup FIB
              </button>
            </div>
          </div>

          {/* Monospace Console Stream */}
          <div className="bg-black/90 border border-white/10 rounded-xl p-4 font-['JetBrains_Mono'] text-xs text-zinc-300 h-44 overflow-y-auto space-y-1.5 select-text">
            {traceLog.length === 0 ? (
              <div className="text-zinc-600 italic">
                // System ready. Select destination node and click &quot;Lookup FIB&quot; or &quot;Inject Topology Churn&quot;.
              </div>
            ) : (
              traceLog.map((line, idx) => (
                <div key={idx} className="leading-relaxed">
                  {line.startsWith('[EVENT]') ? (
                    <span className="text-white font-bold">{line}</span>
                  ) : line.startsWith('[LS-FIB') ? (
                    <span className="text-zinc-200">{line}</span>
                  ) : line.startsWith('[DV-FIB') ? (
                    <span className="text-zinc-300">{line}</span>
                  ) : line.startsWith('[EGRESS RESULT]') ? (
                    <span className="text-white font-extrabold">{line}</span>
                  ) : (
                    <span className="text-zinc-400">{line}</span>
                  )}
                </div>
              ))
            )}
          </div>
        </div>

      </div>
    </section>
  );
};

export default FIBTelemetryTerminal;
